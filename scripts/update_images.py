#!/usr/bin/env python3
"""自动发现上游镜像版本，并改写 images.txt 里被托管的 managed 块。

用法：
    python scripts/update_images.py [--dry-run]
                                    [--config config/tracked-images.yaml]
                                    [--images images.txt]
                                    [--fixture-dir DIR]

设计要点：
  * 只用标准库 + PyYAML（仅用于读配置），不需要 docker / skopeo。
  * 通过 Docker Hub v2 API 拿 tag 列表（含 name / digest / last_updated / images）。
  * "跟随官方默认"：用 latest 的 digest 反查同 digest 的版本 tag，不猜后缀。
  * 变体白名单：后缀不在 preferred_variants 里的 tag 不参与选版
    （否则 -rocm700-ml35x 这类异种构建会靠 .postN 在版本号上胜出）。
  * 保留策略：时间窗 window_days 内、按 group_level 每组取最高版本、
    最多保留 max_versions 个版本行。
  * 只改 managed 块，其它行原样保留；内容无变化则不写盘。
  * 单仓库失败隔离：某个镜像失败时保留它的旧块，继续处理下一个。

环境变量：
  HUB_API_BASE   覆盖 Docker Hub API 基地址（默认 https://hub.docker.com）。
                 用于本地起 mock server 做真实 HTTP 路径的验证，生产勿设。

退出码：
  0  全部成功
  3  部分镜像失败（已成功的部分仍会被写入）
"""

import argparse
import datetime as dt
import json
import os
import re
import sys
import time
import urllib.error
import urllib.parse
import urllib.request

try:
    import yaml
except ImportError:  # 允许在没有 PyYAML 的环境下改用 JSON 配置
    yaml = None

HUB_API_BASE = os.environ.get("HUB_API_BASE", "https://hub.docker.com").rstrip("/")
HUB_TAGS_PATH = (
    "/v2/repositories/{ns}/{repo}/tags?page_size=100&ordering=last_updated"
)
USER_AGENT = "docker-image-pusher-version-sync/1.0"

# v0.25.1 / v0.4.3.post1 / v0.4.3.post1-cu124 / 0.25.1 都能解析
VER_RE = re.compile(
    r"^v?(?P<maj>\d+)\.(?P<min>\d+)"
    r"(?:\.(?P<pat>\d+))?"
    r"(?:\.post(?P<post>\d+))?"
    r"(?P<suffix>[-+].*)?$"
)

BEGIN_PREFIX = "# >>> BEGIN managed:"
END_PREFIX = "# <<< END managed:"
BEGIN_FMT = BEGIN_PREFIX + " docker.io/{src} >>>"
END_FMT = END_PREFIX + " docker.io/{src} <<<"
NOTE_LINE = "# generated by scripts/update_images.py; do not edit manually"


# --------------------------------------------------------------------------- #
# HTTP
# --------------------------------------------------------------------------- #
def http_get_json(url, retries=4, timeout=30):
    """GET 一个 JSON，带指数退避（尊重 Retry-After）。

    注意：timeout 必须是数字（秒）。urlopen 最终会把它交给 socket.settimeout()，
    传元组会抛 TypeError —— 且会被下面的 except Exception 当成网络抖动重试，
    报错信息完全看不出是哪里的问题。
    """
    last_exc = None
    for attempt in range(retries):
        try:
            req = urllib.request.Request(
                url, headers={"User-Agent": USER_AGENT, "Accept": "application/json"}
            )
            with urllib.request.urlopen(req, timeout=timeout) as resp:
                return json.loads(resp.read().decode("utf-8"))
        except urllib.error.HTTPError as exc:
            last_exc = exc
            if exc.code == 429 or 500 <= exc.code < 600:
                retry_after = exc.headers.get("Retry-After") if exc.headers else None
                wait = (
                    int(retry_after)
                    if retry_after and str(retry_after).isdigit()
                    else 2 ** attempt + 1
                )
                print(
                    f"  ! HTTP {exc.code}, {wait}s 后重试 ({attempt + 1}/{retries})",
                    file=sys.stderr,
                )
                time.sleep(wait)
                continue
            raise
        except Exception as exc:  # 网络抖动 / 超时 / 响应体不是 JSON
            last_exc = exc
            # TypeError / AttributeError / KeyError 是代码写错了，不是网络问题：
            # 立刻暴露，别伪装成"重试 4 次后失败"。
            # （JSONDecodeError 是 ValueError 子类，属上游偶发坏响应，仍应重试。）
            if isinstance(exc, (TypeError, AttributeError, KeyError)):
                raise
            if attempt == retries - 1:
                raise
            wait = 2 ** attempt + 1
            print(f"  ! {exc!r}, {wait}s 后重试 ({attempt + 1}/{retries})", file=sys.stderr)
            time.sleep(wait)
    raise last_exc


def _rows_from_results(results):
    floor = dt.datetime.min.replace(tzinfo=dt.timezone.utc)
    out = []
    for item in results:
        ts = item.get("last_updated")
        when = floor
        if ts:
            try:
                when = dt.datetime.fromisoformat(ts.replace("Z", "+00:00"))
            except ValueError:
                when = floor
        out.append(
            {
                "name": item.get("name", ""),
                "digest": (item.get("digest") or "").strip(),
                "images": item.get("images") or [],
                "last_updated": when,
            }
        )
    return out


def fetch_tags(ns, repo, window_days, fixture_dir=None, max_pages=20):
    """拿某个仓库的 tag 列表。fixture_dir 用于离线测试。"""
    if fixture_dir:
        path = os.path.join(fixture_dir, f"{ns}__{repo}.json")
        with open(path, encoding="utf-8") as fh:
            payload = json.load(fh)
        pages = payload if isinstance(payload, list) else [payload]
        rows = []
        for page in pages:
            rows.extend(_rows_from_results(page.get("results", [])))
        return rows

    cutoff = dt.datetime.now(dt.timezone.utc) - dt.timedelta(days=window_days)
    url = HUB_API_BASE + HUB_TAGS_PATH.format(
        ns=urllib.parse.quote(ns), repo=urllib.parse.quote(repo)
    )
    rows = []
    page = 0
    while url and page < max_pages:
        payload = http_get_json(url)
        batch = _rows_from_results(payload.get("results", []))
        rows.extend(batch)
        page += 1
        # 结果按 last_updated 降序；整页都超出时间窗、且已见到 latest，就可以停了
        seen_latest = any(r["name"] == "latest" for r in rows)
        if batch and seen_latest and all(r["last_updated"] < cutoff for r in batch):
            break
        url = payload.get("next")
    return rows


# --------------------------------------------------------------------------- #
# 版本解析与选择
# --------------------------------------------------------------------------- #
def parse_ver(name):
    """返回 (major, minor, patch, post, suffix)，不是版本号则返回 None。"""
    m = VER_RE.match(name)
    if not m:
        return None
    return (
        int(m.group("maj")),
        int(m.group("min")),
        int(m.group("pat") or 0),
        int(m.group("post") or 0),
        m.group("suffix") or "",
    )


def variant_rank(suffix, preferred):
    """后缀优先级：越靠前越小；不在列表里的排到最后。"""
    try:
        return preferred.index(suffix)
    except ValueError:
        return len(preferred) + (0 if suffix == "" else 1)


def variant_allowed(suffix, preferred):
    """后缀是否在白名单里。不在白名单的变体（如 -rocm700-ml35x）直接不参与选版。"""
    return suffix in preferred


def choose_latest_version(rows, preferred):
    """用 latest 的 digest 反查出对应的版本 tag。返回 (tag_name | None, 说明)。"""
    latest = next((r for r in rows if r["name"] == "latest"), None)
    if latest is None or not latest["digest"]:
        return None, "no-latest"

    # 1) 精确匹配：顶层 digest 相同
    hits = [
        r
        for r in rows
        if r["name"] != "latest" and r["digest"] == latest["digest"] and parse_ver(r["name"])
    ]
    if hits:
        # 优先白名单内的变体；若 latest 恰好只指向一个陌生变体，则如实返回它
        # （因为那就是"官方默认"，不能因为不认识的配置而丢失反查能力）
        allowed = [r for r in hits if variant_allowed(parse_ver(r["name"])[4], preferred)]
        pool = allowed or hits
        pool.sort(
            key=lambda r: (
                variant_rank(parse_ver(r["name"])[4], preferred),
                len(r["name"]),
                r["name"],
            )
        )
        note = f"digest-exact(x{len(hits)})"
        if not allowed:
            note += ",variant-off-list"
        return pool[0]["name"], note

    # 2) 兜底：按 (os, arch) -> digest 的映射完全相等来匹配
    def arch_map(row):
        mapping = {
            (i.get("os"), i.get("architecture")): i.get("digest")
            for i in row["images"]
        }
        return {k: v for k, v in mapping.items() if v}

    latest_map = arch_map(latest)
    if latest_map:
        pool = [
            r
            for r in rows
            if r["name"] != "latest"
            and parse_ver(r["name"])
            and arch_map(r) == latest_map
        ]
        allowed = [r for r in pool if variant_allowed(parse_ver(r["name"])[4], preferred)]
        for row in allowed or pool:
            return row["name"], "digest-arch"

    return None, "no-match"


LEVEL_WIDTH = {"major": 1, "minor": 2, "patch": 3}


def group_key(ver, level):
    """按配置的粒度取分组键：minor -> (maj,min)，patch -> (maj,min,pat)。"""
    return ver[: LEVEL_WIDTH.get(level, 2)]


def pick_versions(rows, window_days, preferred, group_level="minor", keep_always=()):
    """按 group_level 分组，每组只保留最高版本；按版本降序返回 tag 名。

    变体白名单：后缀不在 preferred_variants 里的 tag 一律不参与选版。
    否则形如 v0.5.15.post1-rocm700-ml35x（AMD ROCm 构建）会靠 .post1 在
    版本号上压过裸 v0.5.15，把一张不该要的镜像推进仓库。
    """
    cutoff = dt.datetime.now(dt.timezone.utc) - dt.timedelta(days=window_days)
    keep_always = set(keep_always)
    best = {}
    for row in rows:
        ver = parse_ver(row["name"])
        if ver is None:
            continue
        if not variant_allowed(ver[4], preferred):
            continue
        if row["last_updated"] < cutoff and row["name"] not in keep_always:
            continue
        key = group_key(ver, group_level)
        score = (ver[:4], -variant_rank(ver[4], preferred))
        if key not in best or score > best[key][0]:
            best[key] = (score, row["name"])
    ordered = sorted(best.values(), key=lambda x: x[0], reverse=True)
    return [name for _, name in ordered]


def _sort_desc(names):
    return sorted(names, key=lambda n: parse_ver(n) or (0,), reverse=True)


def build_block(cfg, rows, window_days, default_limit=None):
    """为单个镜像生成 managed 块（行列表）。"""
    src = cfg["source"]
    preferred = cfg.get("preferred_variants") or [""]
    limit = cfg.get("max_versions", default_limit)

    lines = [BEGIN_FMT.format(src=src), NOTE_LINE]
    if cfg.get("include_latest", True):
        lines.append(f"{src}:latest")

    latest_tag, how = choose_latest_version(rows, preferred)
    names = pick_versions(
        rows,
        window_days,
        preferred,
        group_level=cfg.get("group_level", "minor"),
        keep_always=[latest_tag] if latest_tag else [],
    )
    if latest_tag and latest_tag not in names:
        names.insert(0, latest_tag)

    # 截断到 max_versions 个版本行（不含 :latest）。
    # latest 指向的那个版本必须保留 —— 若它被截掉，就挤掉最低位的那个。
    if limit and limit > 0 and len(names) > limit:
        names = names[:limit]
        if latest_tag and latest_tag not in names:
            names[-1] = latest_tag
        names = _sort_desc(names)

    lines.extend(f"{src}:{name}" for name in names)
    lines.append(END_FMT.format(src=src))
    return lines, how


# --------------------------------------------------------------------------- #
# images.txt 读写
# --------------------------------------------------------------------------- #
def source_of(line):
    """从 images.txt 的一行里解析出 'ns/repo'，与 docker.yaml 的解析保持一致。"""
    text = line.strip()
    if not text or text.startswith("#"):
        return None
    parts = text.split()
    if not parts:
        return None
    image = parts[-1].split("@", 1)[0]
    segs = image.split("/")
    last = segs[-1].split(":", 1)[0]
    if len(segs) == 1:
        return last
    return f"{segs[-2]}/{last}"


def existing_block(path, src):
    """从现有 images.txt 里取出某个 source 的 managed 块（失败时回退用）。"""
    begin = BEGIN_FMT.format(src=src)
    end = END_FMT.format(src=src)
    try:
        with open(path, encoding="utf-8") as fh:
            lines = fh.read().splitlines()
    except OSError:
        return None
    out, inside = [], False
    for line in lines:
        if line.strip() == begin:
            inside = True
            out.append(line)
            continue
        if line.strip() == end and inside:
            out.append(line)
            return out
        if inside:
            out.append(line)
    return None


def rewrite_images(path, blocks, managed_sources, dry_run=False):
    """重写 images.txt：删掉旧 managed 块与被托管的散落行，再插入新块。"""
    with open(path, encoding="utf-8") as fh:
        original = fh.read()

    kept, insert_at, inside = [], None, False
    for line in original.splitlines():
        stripped = line.strip()
        if stripped.startswith(BEGIN_PREFIX):
            inside = True
            if insert_at is None:
                insert_at = len(kept)
            continue
        if stripped.startswith(END_PREFIX):
            inside = False
            continue
        if inside:
            continue
        if source_of(line) in managed_sources:
            if insert_at is None:
                insert_at = len(kept)
            continue
        kept.append(line)

    if insert_at is None:
        insert_at = len(kept)

    head, tail = kept[:insert_at], kept[insert_at:]
    while head and not head[-1].strip():
        head.pop()
    while tail and not tail[0].strip():
        tail.pop(0)

    out = list(head)
    if out:
        out.append("")
    for idx, block in enumerate(blocks):
        out.extend(block)
        if idx != len(blocks) - 1:
            out.append("")
    if tail:
        out.append("")
        out.extend(tail)

    collapsed = []
    for line in out:
        if not line.strip() and collapsed and not collapsed[-1].strip():
            continue
        collapsed.append(line)

    text = "\n".join(collapsed).rstrip("\n") + "\n"
    changed = text != original
    if changed and not dry_run:
        with open(path, "w", encoding="utf-8") as fh:
            fh.write(text)
    return changed, text


# --------------------------------------------------------------------------- #
# 入口
# --------------------------------------------------------------------------- #
def load_config(path):
    with open(path, encoding="utf-8") as fh:
        raw = fh.read()
    if yaml is not None:
        return yaml.safe_load(raw)
    return json.loads(raw)


def emit_github_output(changed):
    path = os.environ.get("GITHUB_OUTPUT")
    if not path:
        return
    try:
        with open(path, "a", encoding="utf-8") as fh:
            fh.write(f"changed={'yes' if changed else 'no'}\n")
    except OSError:
        pass


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--config", default="config/tracked-images.yaml")
    parser.add_argument("--images", default="images.txt")
    parser.add_argument("--dry-run", action="store_true")
    parser.add_argument(
        "--fixture-dir",
        default=os.environ.get("HUB_FIXTURE_DIR"),
        help="离线测试：从该目录读取 <ns>__<repo>.json 代替真实 HTTP 请求",
    )
    args = parser.parse_args()

    cfg = load_config(args.config)
    window_days = int(cfg.get("window_days", 90))
    default_limit = cfg.get("max_versions")

    results = {}
    failures = 0
    for item in cfg["images"]:
        src = item["source"]
        ns, _, repo = src.partition("/")
        try:
            rows = fetch_tags(ns, repo, window_days, fixture_dir=args.fixture_dir)
            if not rows:
                raise RuntimeError("上游返回空 tag 列表")
            block, how = build_block(item, rows, window_days, default_limit)
            if how in ("no-match", "no-latest") and (item.get("fallback") or "hold") == "hold":
                fallback = existing_block(args.images, src)
                print(
                    f"[hold] {src}: latest 无法反查出对应版本（{how}），本轮不动",
                    file=sys.stderr,
                )
                if fallback:
                    results[src] = fallback
                continue
            version_count = sum(
                1 for line in block if not line.startswith("#") and not line.endswith(":latest")
            )
            results[src] = block
            print(
                f"[ok]   {src}: 匹配方式={how}, 版本行={version_count}"
                f"（上限 {item.get('max_versions', default_limit) or '不限'}）"
            )
        except Exception as exc:
            failures += 1
            print(f"[warn] {src}: {exc} —— 保留原有内容", file=sys.stderr)
            fallback = existing_block(args.images, src)
            if fallback:
                results[src] = fallback

    managed = set(results)
    blocks = [results[i["source"]] for i in cfg["images"] if i["source"] in results]

    changed, text = rewrite_images(args.images, blocks, managed, dry_run=args.dry_run)
    if args.dry_run:
        print("\n----- images.txt (dry-run) -----")
        print(text)
    print(f"IMAGES_CHANGED={'1' if changed else '0'}")
    emit_github_output(changed)
    return 0 if failures == 0 else 3


if __name__ == "__main__":
    sys.exit(main())
